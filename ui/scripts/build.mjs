// Builds ui/src/generated/{themes.css,tokens.ts} from ui/tokens/swasthya.tokens.json.
// Fails when any built-in theme misses a required contrast pair.
//   node ui/scripts/build.mjs          write the files
//   node ui/scripts/build.mjs --check  fail if the files are out of date (CI)

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { baseVars, themeVars, cssBlock, themeSelector } from '../src/compile.ts'
import { check } from '../src/contrast.ts'

const ui = join(dirname(fileURLToPath(import.meta.url)), '..')
const tokens = JSON.parse(readFileSync(join(ui, 'tokens/swasthya.tokens.json'), 'utf8'))
const checkOnly = process.argv.includes('--check')

const failures = []
for (const [id, theme] of Object.entries(tokens.themes)) {
  for (const [mode, colours] of Object.entries(theme.modes)) {
    for (const f of check(colours, tokens.contrast.pairs)) failures.push(`${id}/${mode}: ${f.fg} on ${f.bg} is ${f.got}:1, needs ${f.need}:1`)
  }
}
if (failures.length) {
  console.error('Contrast check failed:\n  ' + failures.join('\n  '))
  process.exit(1)
}

const [firstId, first] = Object.entries(tokens.themes)[0]
let css = '/* Generated by ui/scripts/build.mjs from ui/tokens/swasthya.tokens.json. Do not edit. */\n\n'
css += cssBlock(':root', { ...baseVars(tokens), ...themeVars(tokens.fonts, first, first.defaultMode) })
for (const [id, theme] of Object.entries(tokens.themes)) {
  for (const mode of ['light', 'dark']) css += '\n' + cssBlock(themeSelector(id, mode), themeVars(tokens.fonts, theme, mode))
}

// `$`-prefixed keys are notes for people editing the JSON, not tokens.
const strip = (v) => Array.isArray(v) ? v.map(strip)
  : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).filter(([k]) => !k.startsWith('$')).map(([k, x]) => [k, strip(x)]))
  : v
const rest = strip(tokens)
const ts = `// Generated by ui/scripts/build.mjs from ui/tokens/swasthya.tokens.json. Do not edit.
import type { Tokens } from '../compile.ts'

export const tokens: Tokens = ${JSON.stringify(rest, null, 2)}

export const defaultTheme = ${JSON.stringify(firstId)}
`

const out = join(ui, 'src/generated')
const files = { 'themes.css': css, 'tokens.ts': ts }
if (checkOnly) {
  const stale = Object.entries(files).filter(([name, text]) => {
    try { return readFileSync(join(out, name), 'utf8') !== text } catch { return true }
  })
  if (stale.length) {
    console.error(`Out of date: ${stale.map(([n]) => n).join(', ')}. Run node ui/scripts/build.mjs`)
    process.exit(1)
  }
  console.log('Tokens up to date; contrast passes for every theme and mode.')
} else {
  mkdirSync(out, { recursive: true })
  for (const [name, text] of Object.entries(files)) writeFileSync(join(out, name), text)
  console.log(`Wrote ${Object.keys(files).join(', ')}; contrast passes for every theme and mode.`)
}
